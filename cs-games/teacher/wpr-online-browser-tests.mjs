import {startDev} from '../../wpr-games/workplace-readiness/service/dev.mjs';
const require=createRequire(new URL('../../wpr-games/workplace-readiness/package.json',import.meta.url));
const {launch}=require('./tests/browser/harness.js');
const axe=readFileSync(require.resolve('axe-core/axe.min.js'),'utf8');
const token='local-browser-test-secret-12345678';
const wait = (page,selector) => page.waitForSelector(selector,{visible:true,timeout:10000});
const exactButton = async (page,text,scope='body') => {
  const hit = await page.waitForFunction((text,scope)=>Array.from(document.querySelectorAll(scope+' button')).some(b=>b.textContent===text&&b.offsetWidth&&!b.disabled),{timeout:10000},text,scope);
  await hit.dispose();
  const buttons=await page.$$(scope+' button');
  for(const b of buttons) if(await b.evaluate((x,t)=>x.textContent===t&&x.offsetWidth&&!x.disabled,text)) {await b.click();return;}
  throw new Error('Missing button '+text);
};
async function a11y(page,selector) {
  await page.evaluate(axe);
  const failures=await page.evaluate(async s=>(await axe.run(s)).violations.map(v=>({id:v.id,targets:v.nodes.map(n=>n.target)})),selector);
  assert.deepEqual(failures,[]);
}
test('teacher publishes exact three-topic diagnostic, student takes it, teacher links class remediation', {timeout:90000}, async t=>{
  const {url,server,db}=await startDev({teacherTokens:{teacher:token}});
  t.after(()=>{server.close();db.close();});
  const browser=await launch();
  t.after(()=>browser.close());
  const teacher=await browser.newPage(), studentContext=await browser.createBrowserContext();
  const student=await studentContext.newPage();
  await student.setViewport({width:360,height:780});
  const errors=[];
  for(const p of [teacher,student]) p.on('pageerror',e=>errors.push(e.message));
  await teacher.goto(url+'/cs-games/teacher/',{waitUntil:'load'});
  await wait(teacher,'#wpr-builder-form');
  await teacher.type('[name="teacher-key"]',token);
  await exactButton(teacher,'Sign in to development service');
  await teacher.waitForSelector('#wpr-active-report');
  await teacher.select('#wpr-quotas select','topic:attire-ppe');
  await exactButton(teacher,'Add coverage group');
  await teacher.select('#wpr-quotas .wpr-quota:nth-child(2) select','topic:workplace-relationships');
  await exactButton(teacher,'Add coverage group');
  await teacher.select('#wpr-quotas .wpr-quota:nth-child(3) select','topic:computer-technology');
  await teacher.evaluate(()=>{
    for(const e of document.querySelectorAll('[name="quota-count"]')) e.value='3';
    document.querySelector('#wpr-builder-form [name="shuffle"]').checked=false;
  });
  await exactButton(teacher,'Generate / regenerate assessment');
  await wait(teacher,'#wpr-online-preview details');
  assert.equal(await teacher.$$eval('#wpr-online-preview details',d=>d.length),9);
  await teacher.click('#wpr-online-preview details summary');
  await exactButton(teacher,'Regenerate question 1');
  await exactButton(teacher,'Publish online assignment');
  const share=await teacher.waitForSelector('a[href*="?assignment="]',{timeout:10000});
  const link=await share.evaluate(x=>x.href);
  const assignmentId=new URL(link).searchParams.get('assignment');
  const a=JSON.parse(db.prepare('SELECT snapshot FROM assignments WHERE id=?').get(assignmentId).snapshot);
  assert.equal(a.questions.length,9);
  await student.goto(link,{waitUntil:'load'});
  await exactButton(student,'Start assessment');
  await a11y(student,'#assignment-body');
  const answers=a.questions.map((q,i)=>i<3?(q.correctIndex+1)%4:q.correctIndex);
  for (const answer of answers) {
    await wait(student,'#assignment-body .wpr-answer');
    await student.click('#assignment-body input[value="'+answer+'"]');
    await exactButton(student,'Save answer','#assignment-body');
    assert.equal(await student.$('#assignment-body .feedback'),null);
  }
  await exactButton(student,'Submit and view results');
  await student.waitForFunction(()=>document.querySelector('#assignment-body h1')?.textContent.endsWith(' results'),{timeout:10000});
  assert.match(await student.$eval('#assignment-body',e=>e.textContent),/6 correct of 9 attempted/);
  await a11y(student,'#assignment-body');
  const remediation=await student.$eval('#assignment-body a[href*="topics=attire-ppe"]',e=>e.href);
  await student.goto(remediation,{waitUntil:'load'});
  await wait(student,'#targeted-options input[value="attire-ppe"]');
  assert.equal(await student.$eval('#targeted-options input[value="attire-ppe"]',e=>e.checked),true);
  await exactButton(student,'Start shared practice');
  assert.equal(await student.evaluate(()=>WRG.app.state().current.tags.some(t=>t.topicId==='attire-ppe')),true);
  assert.equal(await student.evaluate(()=>document.documentElement.scrollWidth),360);
  await student.goto(url+'/wpr-games/workplace-readiness/?practice=1&topics=workplace-relationships&subtopics=management-conflict&difficulty=intermediate&modes=decision',{waitUntil:'load'});
  await exactButton(student,'Start shared practice');
  assert.equal(await student.evaluate(()=>{const c=WRG.app.state().current;return c.difficulty==='intermediate'&&c.mode==='decision'&&c.tags.some(t=>t.subtopicId==='management-conflict');}),true);
  await student.goto(url+'/wpr-games/workplace-readiness/#/summary',{waitUntil:'load'});
  await wait(student,'#readiness-body .wpr-table-scroll');
  assert.match(await student.$eval('#readiness-body',e=>e.textContent),/Classroom diagnostic|Workplace Readiness Diagnostic/);
  assert.equal(await student.evaluate(()=>document.documentElement.scrollWidth),360);
  const downloadDir=mkdtempSync(join(tmpdir(),'wpr-browser-'));
  t.after(()=>rmSync(downloadDir,{recursive:true,force:true}));
  const cdp=await student.createCDPSession();
  await cdp.send('Page.setDownloadBehavior',{behavior:'allow',downloadPath:downloadDir});
  await exactButton(student,'CSV','#readiness-body');
  await exactButton(student,'Save readiness backup');
  const backup=join(downloadDir,'wpr-readiness-backup.json'), exportPath=join(downloadDir,'wpr-performance.csv');
  for(let attempt=0;attempt<40&&(!existsSync(backup)||!existsSync(exportPath));attempt++) await delay(50);
  assert.match(readFileSync(exportPath,'utf8'),/schema_version.*recommended_practice_link/);
  assert.match(readFileSync(exportPath,'utf8'),/topics=attire-ppe[^"]*practice=1/);
  assert.equal(JSON.parse(readFileSync(backup,'utf8')).reports[0].c,6);
  await student.evaluate(()=>localStorage.removeItem('wrg.readiness.v1'));
  await student.reload({waitUntil:'load'});
  await student.waitForFunction(()=>document.querySelector('#readiness-body')?.textContent.includes('Complete a teacher assignment'));
  student.once('dialog',d=>d.accept());
  const uploader=await student.waitForSelector('#readiness-body input[type=file]');
  await uploader.uploadFile(backup);
  await student.waitForFunction(()=>document.querySelector('#readiness-body')?.textContent.includes('Assessment history'));
  const api='/api/wpr/student/'+assignmentId;
  for(let i=0;i<4;i++){
    const post=async(path,body)=>await (await fetch(url+api+path,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(body)})).json();
    const attempt=await post('/start',{browser:randomUUID()});
    await post('/submit',{token:attempt.token,answers});
  }
  await exactButton(teacher,'Class report');
  await teacher.waitForFunction(()=>document.querySelector('#wpr-active-report')?.textContent.includes('5 completed submissions'),{timeout:10000});
  await exactButton(teacher,'Create targeted practice');
  assert.equal(await teacher.$eval('#wpr-builder-form [name="kind"]',e=>e.value),'practice');
  assert.equal(await teacher.$eval('#wpr-quotas select',e=>e.value),'topic:attire-ppe');
  await exactButton(teacher,'Generate / regenerate assessment');
  await exactButton(teacher,'Publish online assignment');
  assert.equal(await teacher.$eval('#download',e=>e.textContent),'Download Canvas QTI ZIP');
  assert.deepEqual(errors,[]);
});
