'use strict';
/* Runs every suite and tool, then writes TEST_RESULTS.md from the real output. */
const cp = require('child_process'), fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
function run(cmd) { const t = Date.now(); const r = cp.spawnSync('sh', ['-c', cmd], { cwd: root, encoding: 'utf8', maxBuffer: 1e8 }); return { out: (r.stdout || '') + (r.stderr || ''), code: r.status, ms: Date.now() - t }; }
function tap(out) { const g = k => { const m = new RegExp('^# ' + k + ' (\\d+)', 'm').exec(out); return m ? +m[1] : 0; }; return { tests: g('tests'), pass: g('pass'), fail: g('fail') }; }
const suites = [
  ['core.test.js', 'Random numbers, expression evaluator, text resolver, ordering logic'],
  ['validator.test.js', 'Template and instance validation, including deliberately broken content that must be rejected'],
  ['generator.test.js', 'Determinism, filters, rotation, spacing, bulk generation, numeric variation, rejection'],
  ['grader.test.js', 'Correct and incorrect grading in all modes, every ordering permutation, feedback matching'],
  ['app-logic.test.js', 'Session tracking, idle-aware active time, storage, privacy, 6,000-challenge long session'],
  ['audit.test.js', '2,400-challenge volume audit, all 22 skills, all modes, difficulties and contexts, repetition'],
  ['browser/app.test.js', 'Real Chromium: play-through, keyboard, drag, persistence, reset, accessibility (axe), layouts, long session']
];
let md = '# Test results\n\nGenerated by `tools/run-report.js`. Each figure below comes from an actual run, not from this document being edited by hand.\n\n';
md += `- Date: ${new Date().toISOString().slice(0, 10)}\n- Node: ${process.version}\n\n`;
md += '## Automated suites\n\n| Suite | What it covers | Tests | Passed | Failed | Time |\n|---|---|---:|---:|---:|---:|\n';
let T = 0, P = 0, F = 0;
suites.forEach(([f, d]) => {
  const r = run('node --test tests/' + f), t = tap(r.out); T += t.tests; P += t.pass; F += t.fail;
  md += `| ${f} | ${d} | ${t.tests} | ${t.pass} | ${t.fail} | ${(r.ms / 1000).toFixed(1)} s |\n`;
});
md += `| **Total** | | **${T}** | **${P}** | **${F}** | |\n\n`;
const v = run('node tools/validate.js'), sw = run('node tools/sweep.js 150');
md += '## Content validation\n\n```\n' + v.out.trim() + '\n```\n\n';
md += '## Instance sweep\n\nEvery template rendered 150 times across every setting it allows, each instance validated.\n\n```\n' + sw.out.trim().split('\n').slice(0, 6).join('\n') + '\n```\n\n';
md += '## Coverage matrix (tools/coverage.js)\n\n```\n' + run('node tools/coverage.js').out.trim() + '\n```\n\n';
md += '## What the tests do not prove\n\n';
md += '- Browser tests ran in **headless Chromium on Linux** only. Safari, Firefox, real Chromebooks, real touch hardware and screen readers (NVDA, JAWS, VoiceOver, ChromeVox) were **not** tested. axe-core automated scanning finds only part of the accessibility issues a person would.\n';
md += '- Layout was tested at 320x568, 360x640, 768x1024 and 1366x768 viewports in an emulator, not on physical devices.\n';
md += '- Active-time idle exclusion is tested with a controlled clock in unit tests, not over real elapsed minutes in a browser.\n';
md += '- Instructional soundness was reviewed by the developer, not independently (see GAME_DESIGN.md).\n';
fs.writeFileSync(path.join(root, 'TEST_RESULTS.md'), md);
console.log('Wrote TEST_RESULTS.md: ' + P + '/' + T + ' passed');
process.exit(F ? 1 : 0);
