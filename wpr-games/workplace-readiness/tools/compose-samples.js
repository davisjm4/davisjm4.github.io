#!/usr/bin/env node
'use strict';
/* Writes SAMPLES.md: representative composed challenges for human review. For every skill, one challenge
 * per mode at a rotating difficulty, plus counterfactual pairs and numeric examples. Deterministic. */
const fs = require('fs'); const path = require('path');
const { loadHybrid } = require('./compose-load.js');
const SEL = require('../js/compose/selector.js');
const S = require('../js/data/schema.js');
const h = loadHybrid();
const L = ['beginner', 'intermediate', 'advanced'];
function fmt(c, title) {
  const o = ['### ' + title, '', '`' + c.reasoning.replace(/^cx:/, '') + '` · ' + S.MODES[c.mode].label + ' · ' + c.difficulty + ' · ' + S.CONTEXTS[c.context], ''];
  if (c.scenario) o.push('> ' + c.scenario, '');
  o.push('**' + c.prompt + '**', '');
  if (c.options) c.options.forEach((x, i) => { const k = c.key.options[x.id]; o.push((x.id === c.key.bestId ? '- ✅ ' : k.role === 'acceptable' ? '- ◐ ' : '- ✗ ') + String.fromCharCode(65 + i) + '. ' + x.text + '  ', '  *' + k.why + (k.misconception ? ' (Misconception: ' + k.misconception + ')' : '') + '*'); });
  if (c.steps) { o.push('Steps as shown: ' + c.steps.map(s => s.text).join(' · '), '', 'One valid order: ' + c.key.example.map(id => c.steps.find(s => s.id === id).text).join(' → '), '');
    c.key.precedence.forEach(p => o.push('- ' + c.steps.find(s => s.id === p.before).text + ' → ' + c.steps.find(s => s.id === p.after).text + ': ' + p.why)); }
  if (c.doc) { o.push('*' + c.doc.title + '*', ''); c.doc.segments.forEach(s => o.push((s.id === c.key.problemId ? '- ❌ ' : '- ') + s.text + (s.id === c.key.problemId ? '  \n  *' + c.key.segments[s.id].note + '*' : ''))); }
  o.push('', 'Takeaway: ' + c.principle, '');
  return o.join('\n');
}
const out = ['# Representative composed challenges', '', 'Generated by `node tools/compose-samples.js` (deterministic). ✅ keyed best answer · ◐ acceptable but not best · ✗ distractor. The code line is the reasoning signature.', ''];
let n = 0;
h.skills.slice().sort((a, b) => a.number - b.number).forEach((s, si) => {
  out.push('## ' + s.number + '. ' + s.name, '');
  Object.keys(S.MODES).forEach((m, mi) => {
    for (let k = 0; k < 3; k++) {
      const lvl = L[(si + mi + k) % 3];
      const us = h.catalog.units.filter(u => u.skill === s.id && u.mode === m && u.difficulty === lvl);
      if (!us.length) continue;
      const u = us[(si * 7 + mi * 3) % us.length];
      out.push(fmt(SEL.renderUnit(h, u, { seed: 'sample' + n }), S.MODES[m].label + ' (' + lvl + ')')); n++; break;
    }
  });
});
out.push('## Counterfactual pairs (one decisive fact changes)', '');
['saf-powered-equipment', 'ctp-deadline-obstacles', 'ise-suspicious-email', 'cus-counter-request'].forEach(kid => {
  const kit = h.catalog.kitsById[kid], is = kit.issues.find(i => i.clear);
  const A = h.catalog.units.find(u => u.kitId === kid && u.mode === 'nextstep' && u.spec.active.join() === is.id && !u.spec.resolved.length);
  const B = h.catalog.units.find(u => u.kitId === kid && u.mode === 'nextstep' && !u.spec.active.length && u.spec.resolved.join() === is.id);
  out.push(fmt(SEL.renderUnit(h, A, { seed: 'cf', contextId: A.hosts[0].context }), kid + ' — ' + is.id + ' NOT satisfied'));
  out.push(fmt(SEL.renderUnit(h, B, { seed: 'cf', contextId: A.hosts[0].context }), kid + ' — ' + is.id + ' satisfied'));
});
['bulk-threshold-cheaper', 'bulk-threshold-not-worth', 'supplier-over-budget', 'supplier-within-budget'].forEach(cid => {
  const u = h.catalog.units.find(x => x.spec.config === cid); out.push(fmt(SEL.renderUnit(h, u, { seed: 'cfn' }), 'Numeric: ' + cid));
});
fs.writeFileSync(path.join(__dirname, '..', 'SAMPLES.md'), out.join('\n'));
console.log('Wrote SAMPLES.md (' + n + ' skill samples + counterfactual pairs)');
