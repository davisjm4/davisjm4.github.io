#!/usr/bin/env node
/* Audits the authored mathematics inventory and model coverage. */
const fs = require('fs');
const path = require('path');
const assert = require('assert');
const root = path.join(__dirname, '..');
const dir = path.join(root, 'content');
const files = fs.readdirSync(dir).filter(f => /^math-.*\.json$/.test(f)).sort();
const bundle = require('../js/data/content-bundle.js');
const Model = require('../js/engine/model.js');
const RNG = require('../js/engine/rng.js');
const idx = Model.indexBundle(bundle);
const all = [];
const report = { ranAt: new Date().toISOString(), topics: [], totals: {} };
const modelTypeCounts = {};
for (const f of files) {
  const records = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
  all.push(...records);
  const topicId = f.slice(0, -5);
  const models = bundle.models.filter(m => m.topicId === topicId);
  const byLevel = Object.fromEntries(['beginner','intermediate','advanced'].map(level => [level, models.filter(m => m.level === level).length]));
  models.forEach(m => { modelTypeCounts[m.questionType] = (modelTypeCounts[m.questionType] || 0) + 1; });
  const uniquePassages = new Set();
  for (const m of models.slice(0, 3)) for (let i = 0; i < 20; i++) uniquePassages.add(Model.buildResponse(idx, m.id, RNG.create('math-audit|' + m.id + '|' + i)).excerpt);
  report.topics.push({
    topicId, records: records.length, uniqueTerms: new Set(records.map(r => r.term.toLowerCase())).size,
    models: models.length, modelsByDifficulty: byLevel,
    uniqueFamilies: new Set(models.map(m => m.family)).size,
    questionTypes: [...new Set(models.map(m => m.questionType))],
    seedSampledExcerptVariants: uniquePassages.size,
    recordIdsUsedAsEvidence: new Set(models.flatMap(m => m.ev)).size
  });
  assert(records.length >= 50, topicId + ': fewer than 50 authored records');
  assert(models.length === 60, topicId + ': expected 60 bounded concept-pair assignments');
  assert(Object.values(byLevel).every(n => n === 20), topicId + ': expected 20 distinct concept-pair assignments per difficulty');
}
const normalizedConcept = r => r.term.toLowerCase().replace(/[^a-z0-9]/g,'') + '|' + r.definition.toLowerCase().replace(/[^a-z0-9]/g,'');
const uniqueConcepts = new Set(all.map(normalizedConcept));
assert(files.length === 8, 'expected eight math topic files; found ' + files.length);
assert(all.length >= 400, 'expected at least 400 records; found ' + all.length);
assert(uniqueConcepts.size >= 400, 'expected 400 distinct term-definition concepts; found ' + uniqueConcepts.size);
report.totals = {
  topics: files.length, authoredRecords: all.length, distinctTermDefinitionConcepts: uniqueConcepts.size,
  topicModels: report.topics.reduce((n, t) => n + t.models, 0),
  reasoningFamilies: new Set(report.topics.flatMap(t => bundle.models.filter(m => m.topicId === t.topicId).map(m => m.family))).size,
  questionTypeCounts: modelTypeCounts,
  duplicateTermDefinitionRecords: all.length - uniqueConcepts.size
};
fs.mkdirSync(path.join(root, 'tests', 'results'), { recursive: true });
fs.writeFileSync(path.join(root, 'tests', 'results', 'math-library.json'), JSON.stringify(report, null, 2));
const lines = [
  '# Mathematics library diversity audit',
  '',
  'Generated by tools/math-audit.js from the authored topic files. Records are counted by distinct normalized term-definition pairs; parameter changes do not create new records.',
  '',
  'Total: **' + report.totals.authoredRecords + ' records**, **' + report.totals.distinctTermDefinitionConcepts + ' distinct term-definition concepts**, **' + report.totals.topicModels + ' question-model combinations**.',
  '',
  '| Topic | Records | Distinct terms | Models | Beginner / Intermediate / Advanced | Families | Sampled excerpt variants* |',
  '|---|---:|---:|---:|---:|---:|---:|'
];
for (const t of report.topics) lines.push('| ' + t.topicId + ' | ' + t.records + ' | ' + t.uniqueTerms + ' | ' + t.models + ' | ' + t.modelsByDifficulty.beginner + ' / ' + t.modelsByDifficulty.intermediate + ' / ' + t.modelsByDifficulty.advanced + ' | ' + t.uniqueFamilies + ' | ' + t.seedSampledExcerptVariants + ' |');
lines.push('', '*Seeded excerpt variation sample: 20 seeds across three models per topic. This measures varied source passages, not new concept records or independently authored reasoning problems.*', '',
  '## What the model count means',
  '',
  'Each topic has 60 bounded model assignments: 20 concept-pair tasks per difficulty. These are **not 60 distinct reasoning families**. Beginner uses definition retrieval and example interpretation; Intermediate uses comparison and misconception analysis; Advanced uses criteria reasoning, example verification, and evidence-limit reasoning. Across the full math library there are **seven genuine model families**, with a third family at Advanced to support consecutive-session variety. Each difficulty has 20 concept pairs; the pairs provide fresh mathematical objects while remaining within these seven reasoning families.',
  '',
  'The evidence for each cited concept combines its concise definition with its authored example. Explanations connect that example to the definition. The 20-problem pool is bounded and supports one no-repeat pass per selected difficulty; longer sessions enter review.',
  '',
  '## Reasoning family inventory');
for (const t of report.topics) {
  const models = bundle.models.filter(m => m.topicId === t.topicId);
  lines.push('', '### ' + t.topicId, '', ...models.map(m => '- **' + m.family + '** (' + m.level + ', ' + m.questionType + '): ' + m.q));
}
fs.writeFileSync(path.join(root, 'MATHEMATICS_DIVERSITY_REPORT.md'), lines.join('\n') + '\n');
console.log('Mathematics audit: ' + report.totals.authoredRecords + ' records, ' + uniqueConcepts.size + ' distinct term-definition concepts, ' + report.totals.topicModels + ' models across ' + files.length + ' topics.');
