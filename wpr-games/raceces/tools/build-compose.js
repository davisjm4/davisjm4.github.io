#!/usr/bin/env node
/* Builds js/data/compose-bundle.js from content/compositional/*.json (the source of truth for
   compositional kits). Never edit the bundle directly; run `npm run build`. */
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const dir = path.join(root, 'content', 'compositional');
const TYPES = ['design', 'process', 'observation'];
const kits = [];
for (const f of fs.readdirSync(dir).filter(f => f.endsWith('.json')).sort()) {
  const src = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
  for (const type of TYPES) {
    if (!src[type]) continue;
    kits.push(Object.assign({ id: src.topicId + '-' + type, type, topicId: src.topicId, source: f }, src[type]));
  }
}
const lib = { schemaVersion: 1, kits };
const out = `/* AUTO-GENERATED by tools/build-compose.js from /content/compositional. Do not edit. */
(function (root) {
  var DATA = ${JSON.stringify(lib)};
  if (typeof module === 'object' && module.exports) module.exports = DATA;
  else { root.RACECES = root.RACECES || {}; root.RACECES.COMPOSE_LIBRARY = DATA; }
})(typeof self !== 'undefined' ? self : this);
`;
fs.writeFileSync(path.join(root, 'js', 'data', 'compose-bundle.js'), out);
console.log(`Built compositional bundle: ${kits.length} kits from ${new Set(kits.map(k => k.topicId)).size} topics.`);
