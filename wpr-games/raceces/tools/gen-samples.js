#!/usr/bin/env node
/* Writes samples/GENERATED_EXAMPLES.md (representative, manual-readable output) and
   samples/review-sample.md (a broad random sample for independent human review). */
const fs = require('fs'), path = require('path');
const C = require('../js/compose/compose.js'), RNG = require('../js/engine/rng.js');
const bundle = require('../js/data/content-bundle.js'), lib = require('../js/data/compose-bundle.js');
const cidx = C.index(lib, bundle);
const SL = ['R', 'A', 'C1', 'E1', 'C2', 'E2', 'S'], LBL = { R: 'Restate', A: 'Answer', C1: 'Cite Evidence', E1: 'Explain Evidence', C2: 'Cite Evidence', E2: 'Explain Evidence', S: 'Summarize' };
const title = id => bundle.topics.find(t => t.id === id);
function render(e, seed, withDistractors) {
  const r = C.buildResponse(cidx, e.id, RNG.create(seed));
  const t = title(e.topicId), st = C.STRUCT_BY_ID[e.structure];
  let s = '### ' + t.subject + ' — ' + t.title + ' (' + e.level + ')\n\n';
  s += '*Reasoning structure:* **' + st.label + '** (`' + e.structure + '`, family `' + e.family + '`)  \n*Configuration:* `' + e.id + '`' + (r.dependency ? '  \n*Order dependency:* evidence pair 1 must come first.' : '') + '\n\n';
  s += '**Source passage.** ' + r.excerpt + '\n\n**Writing question.** ' + r.question + '\n\n';
  SL.forEach(k => { s += '- **' + LBL[k] + ':** ' + r.sentences[k].text + '\n'; });
  if (withDistractors) {
    const d = r.distractors;
    s += '\n*Distractors the engine can draw (each tied to a misconception):*\n\n';
    s += '- Repeats evidence instead of explaining: ' + d.rep[0] + '\n- Explanation tied to the other evidence: ' + d.crossExp[0] + '\n- Unsupported claim: ' + d.bad + '\n- True but does not answer: ' + d.nonAnswer + '\n- Restates a different focus: ' + d.badRestate + '\n- Relevant-looking but off-topic evidence: ' + d.offEv + '\n- Summary that adds new information: ' + d.sumNew + '\n';
  }
  return s + '\n';
}
const pick = (topic, structure, level) => cidx.entries.find(e => e.topicId === topic && e.structure === structure && (!level || e.level === level));
const show = [
  ['honeybees', 'design-function'], ['honeybees', 'design-tradeoff'], ['honeybees', 'observation-competing'],
  ['water-cycle', 'process-sequence'], ['water-cycle', 'design-compare-settings'], ['water-cycle', 'process-rate-confound'],
  ['mars-rovers', 'design-test-result'], ['mars-rovers', 'process-bottleneck'], ['mars-rovers', 'observation-prediction'],
  ['binary-numbers', 'design-feature-need'], ['binary-numbers', 'process-condition-loss'], ['binary-numbers', 'process-chain'],
  ['rust', 'process-rate'], ['rust', 'design-unfair-test'],
  ['arch-bridges', 'design-priority'], ['coral-reefs', 'observation-pattern'], ['public-libraries', 'design-select-features'], ['levers', 'design-competing']
];
let md = '# Representative generated examples\n\n_Generated by `tools/gen-samples.js` from the live engine (seed `sample`). Every example passed the automated checks; the checks cannot certify that wording is natural, so a teacher review is still recommended (see `review-sample.md`)._\n\n';
md += 'The examples within one subject use **different reasoning structures**, not renamed copies of one passage: compare the three Biology examples (function, trade-off, competing explanations) or the three Computer technology examples (single feature, consequence of a missing condition, order-dependent causal chain).\n\n';
show.forEach(([t, s], i) => { const e = pick(t, s); if (e) md += render(e, 'sample', i % 3 === 0); });
fs.mkdirSync(path.join(__dirname, '..', 'samples'), { recursive: true });
fs.writeFileSync(path.join(__dirname, '..', 'samples', 'GENERATED_EXAMPLES.md'), md);
// Broad review sample: 2 random configurations per topic and level.
const rng = RNG.create('review');
let rv = '# Review sample (90 generated responses: 2 per topic per difficulty)\n\n_For human review of coherence, ambiguity, tone and accuracy. Generated by `tools/gen-samples.js`._\n\n';
bundle.topics.forEach(t => ['beginner', 'intermediate', 'advanced'].forEach(l => {
  rng.sample(cidx.entries.filter(e => e.topicId === t.id && e.level === l), 2).forEach(e => { rv += render(e, 'review-' + e.id.length, false); });
}));
fs.writeFileSync(path.join(__dirname, '..', 'samples', 'review-sample.md'), rv);
console.log('Wrote samples/GENERATED_EXAMPLES.md (' + show.length + ' examples) and samples/review-sample.md (90 responses).');
